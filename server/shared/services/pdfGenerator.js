/**
 * PDF Generator Service
 * Generates wage slips, BOCW claims, grievance reports using PDFKit.
 */

const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const PDF_DIR = path.join(__dirname, '..', '..', 'public', 'pdfs');

// Ensure PDF directory exists
if (!fs.existsSync(PDF_DIR)) {
  fs.mkdirSync(PDF_DIR, { recursive: true });
}

/**
 * Generate a wage dispute PDF.
 */
function generateDisputePDF(dispute) {
  return new Promise((resolve, reject) => {
    const filename = `dispute_${dispute.disputeId}_${Date.now()}.pdf`;
    const filepath = path.join(PDF_DIR, filename);
    const doc = new PDFDocument({ margin: 50 });
    const stream = fs.createWriteStream(filepath);

    doc.pipe(stream);

    doc.fontSize(20).text('Swaraj-ID — Wage Dispute Report', { align: 'center' });
    doc.moveDown();
    doc.fontSize(12).text(`Dispute ID: ${dispute.disputeId}`);
    doc.text(`Date: ${new Date().toLocaleDateString('en-IN')}`);
    doc.moveDown();
    doc.text(`Worker: ${dispute.workerName}`);
    doc.text(`Worker ID: ${dispute.workerId}`);
    doc.text(`Phone: ${dispute.phone}`);
    doc.moveDown();
    doc.text(`Unpaid Days: ${dispute.unpaidDays}`);
    doc.text(`Average Rate: ₹${dispute.avgRate}/day`);
    doc.text(`Total Dues: ₹${dispute.totalDues}`);
    doc.moveDown();
    doc.text(`Status: ${dispute.status}`);

    if (dispute.complaintDraft) {
      doc.moveDown();
      doc.fontSize(14).text('Complaint Draft:');
      doc.fontSize(10).text(dispute.complaintDraft);
    }

    doc.moveDown(2);
    doc.fontSize(8).text('Generated by Swaraj-ID Platform. This document is digitally verifiable via blockchain.', { align: 'center' });

    doc.end();
    stream.on('finish', () => resolve(`/pdfs/${filename}`));
    stream.on('error', reject);
  });
}

/**
 * Generate a scheme application PDF.
 */
function generateSchemeApplicationPDF(worker, schemeName, details = {}) {
  return new Promise((resolve, reject) => {
    const filename = `scheme_${schemeName}_${worker.workerId}_${Date.now()}.pdf`;
    const filepath = path.join(PDF_DIR, filename);
    const doc = new PDFDocument({ margin: 50 });
    const stream = fs.createWriteStream(filepath);

    doc.pipe(stream);

    doc.fontSize(20).text(`Swaraj-ID — ${schemeName} Application`, { align: 'center' });
    doc.moveDown();
    doc.fontSize(12).text(`Date: ${new Date().toLocaleDateString('en-IN')}`);
    doc.moveDown();
    doc.text(`Worker: ${worker.name}`);
    doc.text(`Worker ID: ${worker.workerId}`);
    doc.text(`Phone: ${worker.phone}`);
    doc.text(`City: ${worker.city}`);
    doc.text(`Work Type: ${worker.workType}`);
    doc.text(`Swaraj Score: ${worker.swarajScore}`);
    doc.moveDown();

    if (details.eligibilityProof) {
      doc.text(`Eligibility verified via zk-SNARK proof`);
      doc.text(`Proof Hash: ${details.eligibilityProof}`);
    }

    doc.moveDown(2);
    doc.fontSize(8).text('Verified by Swaraj-ID blockchain. No personal data shared — zero-knowledge proof based.', { align: 'center' });

    doc.end();
    stream.on('finish', () => resolve(`/pdfs/${filename}`));
    stream.on('error', reject);
  });
}

/**
 * Generate a grievance report PDF.
 */
function generateGrievancePDF(grievance) {
  return new Promise((resolve, reject) => {
    const filename = `grievance_${grievance.grievanceId}_${Date.now()}.pdf`;
    const filepath = path.join(PDF_DIR, filename);
    const doc = new PDFDocument({ margin: 50 });
    const stream = fs.createWriteStream(filepath);

    doc.pipe(stream);

    doc.fontSize(20).text('Swaraj-ID — Grievance Report', { align: 'center' });
    doc.moveDown();
    doc.fontSize(12).text(`Grievance ID: ${grievance.grievanceId}`);
    doc.text(`Type: ${grievance.type}`);
    doc.text(`Date: ${new Date().toLocaleDateString('en-IN')}`);
    doc.text(`Anonymous: ${grievance.anonymous ? 'Yes' : 'No'}`);
    doc.text(`Collective: ${grievance.isCollective ? `Yes (${grievance.reportCount} reports)` : 'No'}`);
    doc.moveDown();
    doc.text(`Description: ${grievance.description}`);

    if (grievance.site) doc.text(`Site: ${grievance.site}`);
    if (grievance.pinCode) doc.text(`Pin Code: ${grievance.pinCode}`);

    doc.moveDown(2);
    doc.fontSize(8).text('Filed via Swaraj-ID Platform. Blockchain-anchored evidence bundle.', { align: 'center' });

    doc.end();
    stream.on('finish', () => resolve(`/pdfs/${filename}`));
    stream.on('error', reject);
  });
}

module.exports = {
  generateDisputePDF,
  generateSchemeApplicationPDF,
  generateGrievancePDF,
};
